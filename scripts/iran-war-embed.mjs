// W2: embeds the two frozen files the story serves byte for byte, so the route handlers need no file-system read at run time and the
// bytes (and so the sha256 the page prints) cannot drift with line-ending settings.
//
//   node scripts/iran-war-embed.mjs <w1a-story_chronology.csv> <w1-iran-war-preregistration.md>
//
// Writes src/lib/v2/iran-war-chronology-file.ts and src/lib/v2/iran-war-prereg-file.ts and prints each file's sha256.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';

const [csvPath, mdPath] = process.argv.slice(2);
if (!csvPath || !mdPath) {
  console.error('usage: node scripts/iran-war-embed.mjs <chronology.csv> <preregistration.md>');
  process.exit(2);
}
const out = (name, constName, path, note) => {
  const bytes = readFileSync(path);
  const sha = createHash('sha256').update(bytes).digest('hex');
  const body = `// Generated by scripts/iran-war-embed.mjs. ${note}\n// sha256 ${sha}, ${bytes.length} bytes.\nexport const ${constName} =\n  '${bytes.toString('base64')}';\n`;
  writeFileSync(new URL(`../src/lib/v2/${name}`, import.meta.url), body);
  console.log(`${name}: ${bytes.length} bytes, sha256 ${sha}`);
};
out('iran-war-chronology-file.ts', 'CHRONOLOGY_CSV_B64', csvPath, 'The frozen chronology (399 rows), exactly as committed on rebuild/w1.');
out('iran-war-prereg-file.ts', 'PREREG_MD_B64', mdPath, 'The pre-registration with its dated amendments.');
